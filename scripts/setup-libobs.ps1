# Prepare deps/libobs: headers from obs-studio source + obs.lib generated from installed obs.dll.
# Requires: git, MSVC dumpbin/lib on PATH (run from "x64 Native Tools Command Prompt" or a VS dev shell).
param(
  [string]$ObsTag = "33.0.1",
  [string]$ObsDll = "C:\Program Files\obs-studio\bin\64bit\obs.dll"
)
$ErrorActionPreference = "Stop"
$root = Split-Path $PSScriptRoot -Parent
$dest = Join-Path $root "deps\libobs"
$tmp  = Join-Path $root "deps\_obs-src"

New-Item -ItemType Directory -Force "$dest\include", "$dest\lib" | Out-Null

# No OBS installed (e.g. CI): take obs.dll from the official release zip.
if (-not (Test-Path $ObsDll)) {
  $zip = Join-Path $root "deps\obs-release.zip"
  $ext = Join-Path $root "deps\_obs-release"
  $url = "https://github.com/obsproject/obs-studio/releases/download/$ObsTag/OBS-Studio-$ObsTag-Windows-x64.zip"
  Write-Host "OBS not installed, downloading $url"
  Invoke-WebRequest $url -OutFile $zip
  Expand-Archive $zip $ext -Force
  $found = Get-ChildItem $ext -Recurse -Filter obs.dll | Select-Object -First 1
  if (-not $found) { throw "obs.dll not found in $url" }
  $ObsDll = $found.FullName
}

if (-not (Test-Path $tmp)) {
  git clone --depth 1 --branch $ObsTag --filter=blob:none --sparse https://github.com/obsproject/obs-studio.git $tmp
  git -C $tmp sparse-checkout set libobs
}
Copy-Item "$tmp\libobs\*" "$dest\include" -Recurse -Force

# obsconfig.h is generated by the OBS build; provide a minimal stub
@'
#pragma once
#define OBS_DATA_PATH "data"
#define OBS_INSTALL_PREFIX ""
#define OBS_PLUGIN_PATH "obs-plugins/64bit"
#define OBS_PLUGIN_DESTINATION "obs-plugins/64bit"
'@ | Set-Content "$dest\include\obsconfig.h" -Encoding ascii

# Generate obs.lib from the DLL export table
$exports = dumpbin /exports $ObsDll | ForEach-Object {
  if ($_ -match '^\s+\d+\s+[0-9A-F]+\s+[0-9A-F]{8}\s+(\S+)') { $Matches[1] }
}
$def = Join-Path $dest "lib\obs.def"
@("LIBRARY obs", "EXPORTS") + $exports | Set-Content $def -Encoding ascii
lib /nologo /machine:x64 /def:$def /out:"$dest\lib\obs.lib"
Write-Host "libobs ready: $dest"
